-- STUDENT REGISTRATION AND GRADING MANAGEMENT SYSTEM


CREATE TABLE students (
    student_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    registration_no  VARCHAR2(20) NOT NULL,
    first_name       VARCHAR2(50) NOT NULL,
    last_name        VARCHAR2(50) NOT NULL,
    email            VARCHAR2(100) NOT NULL,
    enrollment_date  DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_students PRIMARY KEY (student_id),
    CONSTRAINT uq_students_regno UNIQUE (registration_no),
    CONSTRAINT uq_students_email UNIQUE (email)
);

CREATE TABLE courses (
    course_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    course_code   VARCHAR2(15) NOT NULL,
    course_name   VARCHAR2(100) NOT NULL,
    credit_hours  NUMBER(2) NOT NULL,
    CONSTRAINT pk_courses PRIMARY KEY (course_id),
    CONSTRAINT uq_courses_code UNIQUE (course_code),
    CONSTRAINT ck_courses_credits CHECK (credit_hours BETWEEN 1 AND 6)
);

CREATE TABLE registrations (
    registration_id  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    student_id       NUMBER NOT NULL,
    course_id        NUMBER NOT NULL,
    registration_date DATE DEFAULT SYSDATE NOT NULL,
    academic_year    VARCHAR2(9) NOT NULL,
    semester         NUMBER(1) NOT NULL,
    CONSTRAINT pk_registrations PRIMARY KEY (registration_id),
    CONSTRAINT fk_reg_student FOREIGN KEY (student_id)
        REFERENCES students(student_id),
    CONSTRAINT fk_reg_course FOREIGN KEY (course_id)
        REFERENCES courses(course_id),
    CONSTRAINT uq_student_course_term
        UNIQUE (student_id, course_id, academic_year, semester),
    CONSTRAINT ck_reg_semester CHECK (semester IN (1, 2))
);

CREATE TABLE grades (
    grade_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    registration_id  NUMBER NOT NULL,
    score            NUMBER(5,2) NOT NULL,
    grade_letter     VARCHAR2(2),
    recorded_at      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_grades PRIMARY KEY (grade_id),
    CONSTRAINT fk_grade_registration FOREIGN KEY (registration_id)
        REFERENCES registrations(registration_id),
    CONSTRAINT uq_grade_registration UNIQUE (registration_id),
    CONSTRAINT ck_grade_score CHECK (score BETWEEN 0 AND 100)
);

